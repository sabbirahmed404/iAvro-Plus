#!/bin/bash
# Regenerate english.txt: common English words that Avro offers as typed
# (e.g. "meeting") instead of transliterating them inside a Bangla sentence.
# Source: English Speller Database (ESDB/SCOWL) size 35, US + British spelling.
# Usage: ./scripts/gen-english-words.sh

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/english.txt"
URL="https://app.aspell.net/create?max_size=35&spelling=US&spelling=GBs&max_variant=0&diacritic=strip&special=hacker&download=wordlist&encoding=utf-8&format=inline"

# Banglish spellings of common Bangla words that are also English words but
# slip past the runtime dictionary check (e.g. "or" → ওর, "dim" → ডিম), and
# words usually written in Bangla script (e.g. "islam" → ইসলাম)
BANGLISH="at dim dos hum nil or ore pate allah islam islamic quran muslim muslims"

# Slurs that ESDB includes
OFFENSIVE="negro negroes"

# Chat and tech words that ESDB doesn't have
EXTRA="${ROOT}/scripts/english-extra.txt"

RAW="$(curl -fsSL "${URL}")"

{
  # The ESDB license requires its notice in all copies
  echo "# Common English words, one per line. Generated by scripts/gen-english-words.sh"
  echo "#"
  awk '/^---$/{exit} {print "# " $0}' <<<"${RAW}" | sed 's/ *$//'
  # ESDB capitalises proper nouns ("English", "Monday"); keep them lowercased
  {
    awk '/^---$/{f=1; next} f' <<<"${RAW}"
    grep -v '^#' "${EXTRA}" | tr -s ' ' '\n'
  } | grep -E '^[A-Za-z][a-z]+$' | tr '[:upper:]' '[:lower:]' \
    | grep -vxF -f <(tr ' ' '\n' <<<"${BANGLISH} ${OFFENSIVE}") | sort -u
} > "${OUT}"

echo "Wrote $(grep -vc '^#' "${OUT}") words to ${OUT}"
